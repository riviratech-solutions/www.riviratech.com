/**
 * API routes for src/pages/panel/admin/QASession.tsx.
 *
 * Mounted by ../../routes.js. Helpers used by several pages (sign-in checks,
 * md5, addactivity, ...) come in through `ctx` from ../../shared/core.js.
 */

module.exports = (router, ctx) => {
    const { db, md5, statusFilter, dateRangeFilter, verifyAccount, addactivity } = ctx;

    /* =====================================================================
       Q & A SESSION  (students ask -> trainers/admin answer)
       ---------------------------------------------------------------------
       Table (created in Postgres, mirrors the trainer_queries conventions):

         qa_sessions(
           id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           q_id TEXT,          -- public id, md5 like the other tables
           mem_id TEXT,        -- STUDENT who asked
           to_id TEXT,         -- TRAINER the question is addressed to
           question TEXT,
           answer TEXT,
           ans_by TEXT,        -- mem_id of the trainer/admin who answered
           datetime TEXT,      -- asked at, unix seconds as text
           ansdatetime TEXT,   -- answered at
           deltime TEXT,
           status TEXT         -- '1' pending, '2' answered, '1D' deleted
         )

       SECURITY — the whole feature hinges on this. The row scope is derived
       ONLY from the session cookies (`key` = the caller's own mem_id, `id` =
       their role), never from the request body, so a trainer cannot read or
       answer another trainer's questions by posting someone else's id:

         admin   (X) -> every row, may filter by trainer, may delete
         trainer (2) -> only rows WHERE to_id  = own mem_id, may answer
         student (1) -> only rows WHERE mem_id = own mem_id, may ask
       ===================================================================== */

    // Scope fragment for the caller's role. Returns a WHERE-ready condition
    // plus its bound param, so no caller can widen its own visibility.
    function qaScope(ustatus, ukey, col = { mem: "mem_id", to: "to_id" }) {
        if (ustatus === "2") return { clause: ` AND ${col.to} = ?`, params: [ukey] };
        if (ustatus === "1") return { clause: ` AND ${col.mem} = ?`, params: [ukey] };
        return { clause: "", params: [] }; // admin
    }

    /* ---- Trainer dropdown -------------------------------------------------
       Students need trainer names to address a question, but /get-trainers is
       admin/trainer-only and returns email + qualification. This exposes only
       what a picker needs (id + name) so opening it to students leaks nothing
       extra. */
    router.post("/qa-trainers", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y,1,2"))) return;

        try {
            const [rows] = await db.promise().query(
                "SELECT mem_id, name FROM members WHERE status = '2' ORDER BY name ASC LIMIT 200",
                []
            );
            return res.json({ success: true, data: rows });
        } catch (err) {
            console.error(err);
            return res.json({ success: false, message: "Database error" });
        }
    });

    /* ---- List -------------------------------------------------------------
       One endpoint for all three roles; the role decides the row scope. */
    router.post("/qa-list", async (req, res) => {
        const { key: ukey, id: ustatus } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y,1,2"))) return;

        try {
            const { q, s, n, tid } = req.body;

            const search = q ? q.trim() : "";
            const sortby = s ? s.trim() : "";
            let page = n ? parseInt(n) : 1;

            let orderBy = "cr.id DESC";
            if (sortby === "Old") orderBy = "cr.id ASC";

            /* Base + search. `1D` rows are soft-deleted and never listed. */
            let where = "WHERE (cr.status='1' OR cr.status='2')";
            let params = [];

            if (search) {
                where =
                    "WHERE (cr.question ILIKE ? OR cr.answer ILIKE ?) AND (cr.status='1' OR cr.status='2')";
                params.push(`%${search}%`);
                params.push(`%${search}%`);
            }

            /* Role scope — cookie-derived, not body-derived. */
            const scope = qaScope(ustatus, ukey, { mem: "cr.mem_id", to: "cr.to_id" });
            where += scope.clause;
            params.push(...scope.params);

            /* Admin-only "check by trainer wise" filter. Ignored for other
               roles, whose scope is already pinned to themselves above. */
            let trainerWhere = "";
            if (ustatus === "X" && tid) {
                trainerWhere = " AND cr.to_id = ?";
                params.push(tid);
            }
            where += trainerWhere;

            /* Shared filters (same helpers the other admin lists use). */
            const dr = dateRangeFilter(req.body.df, req.body.dt);
            params.push(...dr.params);

            const sf = statusFilter(req.body.st); // '1' pending, '2' answered
            const limit = req.body.export_all === "1" ? 5000 : 10; // export_all: the admin's "export all matching rows" (one page)
            const offset = (page - 1) * limit;

            let stats = { pending: 0, answered: 0, total: 0 };

            /* Count every status in scope so the summary keeps its split. */
            const countSql = `
                SELECT COUNT(cr.id) AS total, cr.status
                FROM qa_sessions cr
                ${where} ${dr.clause("cr.datetime")}
                GROUP BY cr.status
                `;

            const [countRows] = await db.promise().query(countSql, params);

            countRows.forEach((row) => {
                if (row.status === "1") stats.pending = row.total;
                if (row.status === "2") stats.answered = row.total;
                stats.total += row.total;
            });

            /* Paginate over the selected status only (already counted above). */
            if (sf.value === "1") stats.total = stats.pending;
            else if (sf.value === "2") stats.total = stats.answered;

            const lastPage = stats.total === 0 ? 0 : Math.ceil(stats.total / limit);
            if (page > lastPage && lastPage > 0) page = lastPage;

            /* members joined twice: the asker and the addressed trainer. Both
               carry `status`/`datetime`, so every column here stays aliased. */
            const dataSql = `
                SELECT
                    cr.*,
                    MAX(st.name) AS sname, MAX(st.email) AS semail,
                    MAX(tr.name) AS tname
                FROM qa_sessions cr
                LEFT JOIN members st ON st.mem_id = cr.mem_id
                LEFT JOIN members tr ON tr.mem_id = cr.to_id
                ${where} ${dr.clause("cr.datetime")} ${sf.clause("cr.status")}
                GROUP BY cr.id
                ORDER BY ${orderBy}
                LIMIT ? OFFSET ?
                `;

            const dataParams = [...params, ...sf.params, limit, offset];
            const [rows] = await db.promise().query(dataSql, dataParams);

            if (rows.length === 0) {
                return res.json({
                    success: false, data: [], stats, page, lastPage,
                    message: "No data found",
                });
            }

            return res.json({ success: true, data: rows, stats, page, lastPage });
        } catch (err) {
            console.error(err);
            return res.json({ success: false, message: "Database error" });
        }
    });

    /* ---- Student asks ---------------------------------------------------- */
    router.post("/qa-ask", async (req, res) => {
        const { key: ukey } = req.cookies;
        if (!(await verifyAccount(req, res, "1"))) return;

        try {
            const { to_id, question } = req.body;

            const qtext = (question || "").trim();
            if (!qtext) return res.json({ success: false, message: "Please enter your question" });
            if (qtext.length > 2000) return res.json({ success: false, message: "Question is too long" });
            if (!to_id) return res.json({ success: false, message: "Please choose a trainer" });

            /* to_id comes from the body, so confirm it really is a trainer —
               otherwise a question could be parked on an arbitrary member id. */
            const [trainer] = await db.promise().query(
                "SELECT mem_id FROM members WHERE mem_id = ? AND status = '2' LIMIT 1",
                [to_id]
            );
            if (trainer.length === 0) {
                return res.json({ success: false, message: "Invalid trainer selected" });
            }

            const datetime = Math.floor(Date.now() / 1000);
            const q_id = md5(ukey + to_id + datetime + Math.random());

            await db.promise().query(
                `INSERT INTO qa_sessions (q_id, mem_id, to_id, question, answer, ans_by, datetime, ansdatetime, deltime, status)
                 VALUES (?,?,?,?,'','',?,'','','1')`,
                [q_id, ukey, to_id, qtext, datetime] // mem_id = the caller, never the body
            );

            //addactivity(ukey, q_id, "qa_sessions", "Asked a question", "", qtext.slice(0, 120));

            return res.json({ success: true, message: "✅ Your question has been sent" });
        } catch (err) {
            console.error(err);
            return res.json({ success: false, message: "Database error" });
        }
    });

    /* ---- Trainer / admin answers ----------------------------------------- */
    router.post("/qa-answer", async (req, res) => {
        const { key: ukey, id: ustatus } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y,2"))) return;

        try {
            const { id, answer } = req.body;

            const atext = (answer || "").trim();
            if (!id) return res.json({ success: false, message: "Missing question" });
            if (!atext) return res.json({ success: false, message: "Please enter an answer" });
            if (atext.length > 5000) return res.json({ success: false, message: "Answer is too long" });

            /* A trainer may only answer what was addressed to them. Enforced in
               the UPDATE itself, so a forged id simply matches zero rows. */
            const scope = ustatus === "2" ? " AND to_id = ?" : "";
            const scopeParams = ustatus === "2" ? [ukey] : [];
            const ansdatetime = Math.floor(Date.now() / 1000);

            const [result] = await db.promise().query(
                `UPDATE qa_sessions
                    SET answer = ?, ans_by = ?, ansdatetime = ?, status = '2'
                  WHERE id = ? AND (status = '1' OR status = '2') ${scope}`,
                [atext, ukey, ansdatetime, id, ...scopeParams]
            );

            if (!result.affectedRows) {
                return res.json({ success: false, message: "Question not found" });
            }

            addactivity(ukey, id, "qa_sessions", "Answered a question", "", atext.slice(0, 120));

            return res.json({
                success: true,
                message: "✅ Answer saved",
                answer: atext,
                ans_by: ukey,
                ansdatetime: String(ansdatetime),
            });
        } catch (err) {
            console.error(err);
            return res.json({ success: false, message: "Database error" });
        }
    });

    /* ---- Admin deletes ---------------------------------------------------- */
    router.post("/qa-delete", async (req, res) => {
        const { key: ukey } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y"))) return;

        try {
            const { id } = req.body;

            if (!id) return res.json({ success: false, message: "Missing question" });

            /* Soft delete, matching contacts/trainer_queries: the row drops out
               of every list but stays recoverable. */
            const deltime = Math.floor(Date.now() / 1000);
            const [result] = await db.promise().query(
                "UPDATE qa_sessions SET status = '1D', deltime = ? WHERE id = ? AND (status = '1' OR status = '2')",
                [deltime, id]
            );

            if (!result.affectedRows) {
                return res.json({ success: false, message: "Question not found" });
            }

            addactivity(ukey, id, "qa_sessions", "Deleted a question", "", "");

            return res.json({ success: true, message: "✅ Question deleted" });
        } catch (err) {
            console.error(err);
            return res.json({ success: false, message: "Database error" });
        }
    });
};

// Tables this page owns: their deleted rows are copied to deleted_records under
// the category "admin/qa-session" (see ../../shared/deleted-records.js).
module.exports.tables = [
    { table: "qa_sessions" },
];
