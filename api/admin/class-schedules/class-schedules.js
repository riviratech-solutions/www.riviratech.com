// -> { ok, value } or { ok: false, message }
function cleanResource(body) {
    const title = clean(body.title, 120);
    if (title.length < 2) return { ok: false, message: "Please enter the title" };
    const description = clean(body.description, 300);
    const input = Array.isArray(body.links) ? body.links : [];
    const links = [];
    for (const l of input) {
        const label = clean(l && l.label, 60);
        const href = typeof (l && l.href) === "string" ? l.href.trim() : "";
        if (!label && !href) continue; // blank line
        if (!label) return { ok: false, message: "Every link needs a button label" };
        let ok = false;
        try { const u = new URL(href); ok = (u.protocol === "https:" || u.protocol === "http:") && href.length <= 500; } catch { ok = false; }
        if (!ok) return { ok: false, message: "'" + label + "' needs a full web address (https://…)" };
        links.push({ label, href });
    }
    if (!links.length) return { ok: false, message: "Add at least one link" };
    if (links.length > 6) return { ok: false, message: "Up to 6 links per resource" };
    const c_id = clean(body.c_id, 100);
    const b_id = c_id ? clean(body.b_id, 100) : ""; // a batch only within a course
    return { ok: true, value: { c_id, b_id, title, description, links } };
}

const clean = (v, max) => (typeof v === "string" ? v.replace(/\s+/g, " ").trim().slice(0, max) : "");

// -> { ok, rows } with only well-formed rows, or { ok: false, message }
function cleanRows(input) {
    if (!Array.isArray(input) || !input.length) return { ok: false, message: "Add at least one class" };
    if (input.length > MAX_ROWS) return { ok: false, message: "Up to " + MAX_ROWS + " classes" };
    const rows = [];
    for (const r of input) {
        const row = {
            day_est: clean(r && r.day_est, TEXT_MAX.day),
            time_est: clean(r && r.time_est, TEXT_MAX.time),
            day_ist: clean(r && r.day_ist, TEXT_MAX.day),
            time_ist: clean(r && r.time_ist, TEXT_MAX.time),
        };
        if (!row.day_est && !row.time_est && !row.day_ist && !row.time_ist) continue; // blank line
        if (!row.day_est || !row.time_est || !row.day_ist || !row.time_ist)
            return { ok: false, message: "Fill in every day and time of each class (EST and IST)" };
        rows.push(row);
    }
    if (!rows.length) return { ok: false, message: "Add at least one class" };
    return { ok: true, rows };
}

const parseRows = (s) => {
    try { const a = JSON.parse(s || "[]"); return Array.isArray(a) ? a : []; } catch { return []; }
};

module.exports = (router, ctx) => {
    const { db, verifyAccount, addactivity } = ctx;
    const q = async (sql, p = []) => (await db.promise().query(sql, p))[0];

    const LIST_SQL = `
        SELECT s.*, c.title AS course_name, b.name AS batch_name, b.sdate AS batch_sdate, b.edate AS batch_edate,
               b.status AS batch_status
        FROM class_schedules s
        LEFT JOIN courses c ON c.req_id = s.c_id
        LEFT JOIN batches b ON b.b_id = s.b_id`;
    const shape = ({ sessions, ...r }) => ({ ...r, rows: parseRows(sessions) });

    /* ---------- admin ---------- */
    router.post("/class-schedules", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const rows = await q(LIST_SQL + " ORDER BY s.updatetime DESC NULLS LAST, s.id DESC");
            res.json({ success: true, data: rows.map(shape) });
        } catch (err) {
            console.error("class-schedules:", err.message);
            res.json({ success: false, message: "Could not load the class schedules" });
        }
    });

    // create (no id) or update (id); one schedule per batch
    router.post("/class-schedules/save", async (req, res) => {
        const { key: ukey } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const id = req.body.id ? Number(req.body.id) : 0;
            const c_id = clean(req.body.c_id, 100);
            const b_id = clean(req.body.b_id, 100);
            if (!c_id) return res.json({ success: false, message: "Please select the course" });
            if (!b_id) return res.json({ success: false, message: "Please select the batch" });

            const [batch] = await q(
                `SELECT b.name, c.title FROM batches b JOIN courses c ON c.req_id = b.c_id
                 WHERE b.b_id = ? AND b.c_id = ? AND b.status <> '1D' LIMIT 1`,
                [b_id, c_id]
            );
            if (!batch) return res.json({ success: false, message: "Please select a batch of this course" });

            const checked = cleanRows(req.body.rows);
            if (!checked.ok) return res.json({ success: false, message: checked.message });
            const intro = clean(req.body.intro, TEXT_MAX.intro);
            const note = clean(req.body.note, TEXT_MAX.note);
            const now = Math.floor(Date.now() / 1000);

            const [taken] = await q("SELECT id FROM class_schedules WHERE b_id = ? LIMIT 1", [b_id]);
            if (taken && taken.id !== id)
                return res.json({ success: false, message: "This batch already has a class schedule — edit that one" });

            let savedId = id;
            if (id) {
                const r = await q(
                    "UPDATE class_schedules SET c_id = ?, b_id = ?, intro = ?, note = ?, sessions = ?, updatetime = ? WHERE id = ?",
                    [c_id, b_id, intro, note, JSON.stringify(checked.rows), now, id]
                );
                if (!r || r.affectedRows !== 1) return res.json({ success: false, message: "This class schedule no longer exists" });
            } else {
                const ins = await q(
                    `INSERT INTO class_schedules (c_id, b_id, intro, note, sessions, datetime, updatetime, status)
                     VALUES (?, ?, ?, ?, ?, ?, ?, '1')`,
                    [c_id, b_id, intro, note, JSON.stringify(checked.rows), now, now]
                );
                savedId = ins && ins.insertId;
            }

            addactivity(ukey, String(savedId), "class-schedules",
                (id ? "Class schedule updated for '" : "Class schedule added for '") + batch.name + "'", "", "");
            const [row] = await q(LIST_SQL + " WHERE s.id = ?", [savedId]);
            res.json({ success: true, message: id ? "Class schedule updated" : "Class schedule added", data: row && shape(row) });
        } catch (err) {
            console.error("class-schedules/save:", err.message);
            res.json({ success: false, message: "Could not save the class schedule" });
        }
    });

    router.post("/class-schedules/toggle", async (req, res) => {
        const { key: ukey } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const id = Number(req.body.id);
            const status = req.body.active ? "1" : "1S";
            const r = await q("UPDATE class_schedules SET status = ?, updatetime = ? WHERE id = ?", [status, Math.floor(Date.now() / 1000), id]);
            if (!r || r.affectedRows !== 1) return res.json({ success: false, message: "This class schedule no longer exists" });
            addactivity(ukey, String(id), "class-schedules", status === "1" ? "Class schedule shown to students" : "Class schedule hidden from students", "", "");
            res.json({ success: true, message: status === "1" ? "Shown to the batch's students" : "Hidden from students" });
        } catch (err) {
            console.error("class-schedules/toggle:", err.message);
            res.json({ success: false, message: "Something went wrong" });
        }
    });

    router.post("/class-schedules/delete", async (req, res) => {
        const { key: ukey } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const id = Number(req.body.id);
            const r = await q("DELETE FROM class_schedules WHERE id = ?", [id]);
            if (!r || r.affectedRows !== 1) return res.json({ success: false, message: "This class schedule no longer exists" });
            addactivity(ukey, String(id), "class-schedules", "Class schedule deleted", "", "");
            res.json({ success: true, message: "Class schedule deleted" });
        } catch (err) {
            console.error("class-schedules/delete:", err.message);
            res.json({ success: false, message: "Something went wrong" });
        }
    });

    /* ---------- admin: course resources ---------- */
    const RES_SQL = `SELECT r.*, c.title AS course_name, b.name AS batch_name FROM course_resources r
        LEFT JOIN courses c ON c.req_id = r.c_id LEFT JOIN batches b ON b.b_id = r.b_id AND r.b_id <> ''`;
    const shapeRes = ({ links, ...r }) => ({ ...r, links: parseRows(links) });

    router.post("/course-resources", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const rows = await q(RES_SQL + " ORDER BY r.sortno, r.id");
            res.json({ success: true, data: rows.map(shapeRes) });
        } catch (err) {
            console.error("course-resources:", err.message);
            res.json({ success: false, message: "Could not load the course resources" });
        }
    });

    // create (no id) or update (id)
    router.post("/course-resources/save", async (req, res) => {
        const { key: ukey } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const id = req.body.id ? Number(req.body.id) : 0;
            const checked = cleanResource(req.body);
            if (!checked.ok) return res.json({ success: false, message: checked.message });
            const v = checked.value;
            if (v.c_id) {
                // a deleted course still counts while its batches are running
                const [c] = await q("SELECT 1 AS ok FROM courses WHERE req_id = ? LIMIT 1", [v.c_id]);
                if (!c) return res.json({ success: false, message: "Please select a valid course" });
            }
            if (v.b_id) {
                const [b] = await q("SELECT 1 AS ok FROM batches WHERE b_id = ? AND c_id = ? AND status <> '1D' LIMIT 1", [v.b_id, v.c_id]);
                if (!b) return res.json({ success: false, message: "Please select a batch of this course" });
            }
            const now = Math.floor(Date.now() / 1000);
            let savedId = id;
            if (id) {
                const r = await q(
                    "UPDATE course_resources SET c_id = ?, b_id = ?, title = ?, description = ?, links = ?, updatetime = ? WHERE id = ?",
                    [v.c_id, v.b_id, v.title, v.description, JSON.stringify(v.links), now, id]
                );
                if (!r || r.affectedRows !== 1) return res.json({ success: false, message: "This resource no longer exists" });
            } else {
                const [[{ m }]] = await db.promise().query("SELECT COALESCE(MAX(sortno), 0)::int AS m FROM course_resources");
                const ins = await q(
                    `INSERT INTO course_resources (c_id, b_id, title, description, links, sortno, datetime, updatetime, status)
                     VALUES (?, ?, ?, ?, ?, ?, ?, ?, '1')`,
                    [v.c_id, v.b_id, v.title, v.description, JSON.stringify(v.links), m + 1, now, now]
                );
                savedId = ins && ins.insertId;
            }
            addactivity(ukey, String(savedId), "class-schedules", (id ? "Course resource updated '" : "Course resource added '") + v.title + "'", "", "");
            const [row] = await q(RES_SQL + " WHERE r.id = ?", [savedId]);
            res.json({ success: true, message: id ? "Resource updated" : "Resource added", data: row && shapeRes(row) });
        } catch (err) {
            console.error("course-resources/save:", err.message);
            res.json({ success: false, message: "Could not save the resource" });
        }
    });

    router.post("/course-resources/toggle", async (req, res) => {
        const { key: ukey } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const id = Number(req.body.id);
            const status = req.body.active ? "1" : "1S";
            const r = await q("UPDATE course_resources SET status = ?, updatetime = ? WHERE id = ?", [status, Math.floor(Date.now() / 1000), id]);
            if (!r || r.affectedRows !== 1) return res.json({ success: false, message: "This resource no longer exists" });
            addactivity(ukey, String(id), "class-schedules", status === "1" ? "Course resource shown to students" : "Course resource hidden from students", "", "");
            res.json({ success: true, message: status === "1" ? "Shown to students" : "Hidden from students" });
        } catch (err) {
            console.error("course-resources/toggle:", err.message);
            res.json({ success: false, message: "Something went wrong" });
        }
    });

    router.post("/course-resources/reorder", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const ids = Array.isArray(req.body.ids) ? req.body.ids.map(Number).filter((n) => Number.isInteger(n) && n > 0).slice(0, 500) : [];
            if (!ids.length) return res.json({ success: false, message: "Nothing to reorder" });
            for (let i = 0; i < ids.length; i++) {
                await q("UPDATE course_resources SET sortno = ? WHERE id = ?", [i + 1, ids[i]]);
            }
            res.json({ success: true, message: "Order saved" });
        } catch (err) {
            console.error("course-resources/reorder:", err.message);
            res.json({ success: false, message: "Could not save the new order" });
        }
    });

    router.post("/course-resources/delete", async (req, res) => {
        const { key: ukey } = req.cookies;
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const id = Number(req.body.id);
            const [row] = await q("SELECT title FROM course_resources WHERE id = ?", [id]);
            const r = await q("DELETE FROM course_resources WHERE id = ?", [id]);
            if (!r || r.affectedRows !== 1) return res.json({ success: false, message: "This resource no longer exists" });
            addactivity(ukey, String(id), "class-schedules", "Course resource deleted '" + (row ? row.title : "") + "'", "", "");
            res.json({ success: true, message: "Resource deleted" });
        } catch (err) {
            console.error("course-resources/delete:", err.message);
            res.json({ success: false, message: "Something went wrong" });
        }
    });

    /* ---------- student: their own batches ---------- */
    router.post("/student/class-schedule", async (req, res) => {
        if (!(await verifyAccount(req, res, "1"))) return;
        try {
            const rows = await q(
                LIST_SQL + `
                JOIN member_courses mc ON mc.b_id = s.b_id AND mc.mem_id = ? AND mc.status = '1'
                WHERE s.status = '1' AND COALESCE(b.status, '') <> '1D'
                ORDER BY b.sdate DESC NULLS LAST, s.id DESC`,
                [req.cookies.key]
            );
            // one card per batch, and only what the page shows
            const seen = new Set();
            const data = rows.filter((r) => !seen.has(r.b_id) && seen.add(r.b_id)).map((r) => ({
                id: r.id, course_name: r.course_name, batch_name: r.batch_name,
                batch_sdate: r.batch_sdate, batch_edate: r.batch_edate,
                intro: r.intro, note: r.note, rows: parseRows(r.sessions),
            }));

            // resources for everyone, for the student's own courses (whole
            // course), and for their own batches
            const resRows = await q(
                `SELECT r.title, r.description, r.links FROM course_resources r
                 WHERE r.status = '1' AND (
                    r.c_id = ''
                    OR (r.b_id = '' AND r.c_id IN (SELECT mc.c_id FROM member_courses mc WHERE mc.mem_id = ? AND mc.status = '1'))
                    OR (r.b_id <> '' AND EXISTS (SELECT 1 FROM member_courses mc
                        WHERE mc.mem_id = ? AND mc.status = '1' AND mc.c_id = r.c_id AND mc.b_id = r.b_id)))
                 ORDER BY r.sortno, r.id`,
                [req.cookies.key, req.cookies.key]
            );
            const resources = resRows.map((r) => ({ title: r.title, description: r.description, links: parseRows(r.links) }));
            res.json({ success: true, data, resources });
        } catch (err) {
            console.error("student/class-schedule:", err.message);
            res.json({ success: false, message: "Could not load your class schedule" });
        }
    });
};

