/**
 * API routes for src/pages/panel/admin/ClassSchedules.tsx (manage) and
 * src/pages/panel/student/ClassSchedule.tsx (the student's view).
 *
 * A class schedule belongs to one batch (also a running batch of a course that
 * was deleted — its students are still enrolled): the weekly session times, shown in
 * EST and IST side by side (the IST day can run a day ahead of the EST one).
 *
 *   class_schedules(id, c_id, b_id, intro, note, sessions, datetime, updatetime, status)
 *     sessions JSON: [{ day_est, time_est, day_ist, time_ist }]
 *     status  '1' shown to the batch's students · '1S' hidden
 *
 * Students: POST /student/class-schedule — the schedules of their own batches
 * (member_courses), shown ones only, plus the course resources for them.
 *
 * Course resources (the "Course resources" card on the student page):
 *   course_resources(id, c_id, b_id, title, description, links, sortno, datetime, updatetime, status)
 *     c_id    '' = every student · a course id = only that course's students
 *     b_id    '' = the whole course · a batch id = only that batch's students
 *     links   JSON: [{ label, href }]  (1–6, http/https only)
 *     status  '1' shown · '1S' hidden
 * The five resources of the course guide are added when the table is created.
 *
 * Mounted by ../../routes.js. Helpers used by several pages (sign-in checks,
 * addactivity, ...) come in through `ctx` from ../../shared/core.js.
 */

const MAX_ROWS = 21;
const TEXT_MAX = { day: 30, time: 40, intro: 300, note: 400 };

async function ensureTable(db) {
    await db.promise().query(`CREATE TABLE IF NOT EXISTS class_schedules (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        c_id TEXT NOT NULL,
        b_id TEXT NOT NULL,
        intro TEXT NOT NULL DEFAULT '',
        note TEXT NOT NULL DEFAULT '',
        sessions TEXT NOT NULL DEFAULT '[]',
        datetime BIGINT,
        updatetime BIGINT,
        status VARCHAR(4) NOT NULL DEFAULT '1'
    )`);
    await db.promise().query("CREATE UNIQUE INDEX IF NOT EXISTS class_schedules_b_id ON class_schedules (b_id)");

    // course resources — the guide's five, added only when the table is new
    // (an admin who deletes them all doesn't get them back on the next start)
    const [[{ t }]] = await db.promise().query("SELECT to_regclass('course_resources') AS t");
    await db.promise().query(`CREATE TABLE IF NOT EXISTS course_resources (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        c_id TEXT NOT NULL DEFAULT '',
        title TEXT NOT NULL,
        description TEXT NOT NULL DEFAULT '',
        links TEXT NOT NULL DEFAULT '[]',
        sortno INTEGER NOT NULL DEFAULT 0,
        datetime BIGINT,
        updatetime BIGINT,
        status VARCHAR(4) NOT NULL DEFAULT '1'
    )`);
    if (!t) {
        const now = Math.floor(Date.now() / 1000);
        for (let i = 0; i < STARTING_RESOURCES.length; i++) {
            const r = STARTING_RESOURCES[i];
            await db.promise().query(
                `INSERT INTO course_resources (c_id, title, description, links, sortno, datetime, updatetime, status)
                 VALUES ('', ?, ?, ?, ?, ?, ?, '1')`,
                [r.title, r.desc, JSON.stringify(r.links), i + 1, now, now]
            );
        }
    }
}

