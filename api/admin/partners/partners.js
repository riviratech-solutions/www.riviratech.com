/**
 * API routes for src/pages/panel/admin/Partners.tsx — the logos in the home
 * page's "Trusted by industry teams & partners" strip (components/TrustedBy.tsx).
 *
 *   partners(id, name, website, logo, sortno, datetime, status)
 *     website  optional link the logo opens ("" = no link)
 *     logo     an upload key (riviratech/partners/…, served from /uploads/) or,
 *              for the starting logos, a site path (/clients/…)
 *     status   '1' shown · '1S' hidden · '1D' deleted
 *
 * Public: GET /get-partners (the home page; cached 10 min by utils/siteCache).
 * The whole strip can be switched off like YouTube / Testimonials
 * (../../website/home/home-sections.js, section "partners").
 *
 * Mounted by ../../routes.js. Helpers used by several pages (sign-in checks,
 * md5, addactivity, ...) come in through `ctx` from ../../shared/core.js.
 */
const homeSections = require("../../website/home/home-sections");

// The logos the strip showed before it was managed here — added once, when the
// table is first created, so the home page looks the same until they're edited.
const STARTING_LOGOS = [
    ["Intellectuals AI Solutions", "/clients/1-sm.webp"],
    ["Succeed E-learning", "/clients/4-sm.webp"],
    ["GokaTech", "/clients/gokatech.webp"],
    ["Discovery Analytics", "/clients/discovery-analytics.webp"],
    ["VINFOTech Solutions LLC", "/clients/vinfotech.webp"],
    ["Vireonix Technologies LLC", "/clients/vireonix.webp"],
];

async function ensureTable(db) {
    const q = (sql, p) => db.promise().query(sql, p);
    await q(`CREATE TABLE IF NOT EXISTS partners (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        website TEXT NOT NULL DEFAULT '',
        logo TEXT NOT NULL DEFAULT '',
        sortno INTEGER NOT NULL DEFAULT 0,
        datetime BIGINT,
        status VARCHAR(4) NOT NULL DEFAULT '1'
    )`);
    const [[{ n }]] = await q(`SELECT COUNT(*)::int AS n FROM partners`);
    if (n === 0) {
        const t = Math.floor(Date.now() / 1000);
        for (let i = 0; i < STARTING_LOGOS.length; i++) {
            await q(`INSERT INTO partners (name, website, logo, sortno, datetime, status) VALUES (?, '', ?, ?, ?, '1')`,
                [STARTING_LOGOS[i][0], STARTING_LOGOS[i][1], i + 1, t]);
        }
    }
}

// Optional website: blank, or a web address (https:// is added when left out).
function cleanWebsite(v) {
    const s = String(v || "").trim();
    if (!s) return { ok: true, value: "" };
    const url = /^https?:\/\//i.test(s) ? s : "https://" + s;
    if (!/^https?:\/\/[^\s/$.?#][^\s]*\.[^\s]{2,}$/i.test(url) || url.length > 500) return { ok: false };
    return { ok: true, value: url };
}

module.exports = (router, ctx) => {
    const { db, verifyAccount, nextSortNo, applyReorder, moveS3File, deleteS3File, addactivity } = ctx;

    // a fresh upload (temp key) moved to its final place; "" when it can't be
    const keepLogo = async (fileKey) => {
        if (typeof fileKey !== "string" || !fileKey.startsWith("riviratech/temp/")) return "";
        return moveS3File(fileKey, "riviratech/partners/" + fileKey.split("/").pop());
    };

    /* ---- Public: the home page strip ---- */
    router.get("/get-partners", async (req, res) => {
        try {
            if (!(await homeSections.isEnabled(db, "partners"))) {
                return res.json({ success: true, enabled: false, data: [] });
            }
            const [rows] = await db.promise().query(
                `SELECT name, website, logo FROM partners WHERE status = '1' AND logo <> '' ORDER BY sortno ASC, id ASC`
            );
            res.json({ success: true, enabled: true, data: rows });
        } catch (err) {
            console.error("get-partners:", err.message);
            res.json({ success: false, data: [] });
        }
    });

    /* ---- Admin ---- */
    router.post("/partners-list", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const [rows] = await db.promise().query(
                `SELECT * FROM partners WHERE status != '1D' ORDER BY sortno ASC, id ASC`
            );
            res.json({ success: true, data: rows });
        } catch (err) {
            console.error(err);
            res.json({ success: false, message: "Failed to load partners" });
        }
    });

    router.post("/partners-add", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const name = String(req.body.name || "").trim();
            if (name.length < 2 || name.length > 120) return res.json({ success: false, message: "Please enter the name" });
            const web = cleanWebsite(req.body.website);
            if (!web.ok) return res.json({ success: false, message: "Please enter a valid website link, or leave it empty" });
            const logo = await keepLogo(req.body.logo_key);
            if (!logo) return res.json({ success: false, message: "Please upload the logo" });

            const datetime = Math.floor(Date.now() / 1000);
            const sortno = await nextSortNo("partners");
            const [r] = await db.promise().query(
                `INSERT INTO partners (name, website, logo, sortno, datetime, status) VALUES (?, ?, ?, ?, ?, '1')`,
                [name, web.value, logo, sortno, datetime]
            );
            const [rows] = await db.promise().query(`SELECT * FROM partners WHERE id = ?`, [r.insertId]);
            addactivity(req.cookies.key, String(r.insertId), "partners", "Partner added '" + name + "'", "", "");
            res.json({ success: true, data: rows[0], message: "Partner added" });
        } catch (err) {
            console.error(err);
            res.json({ success: false, message: "Something went wrong" });
        }
    });

    router.post("/partners-update", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const id = parseInt(req.body.id, 10);
            if (!id) return res.json({ success: false, message: "Invalid id" });
            const name = String(req.body.name || "").trim();
            if (name.length < 2 || name.length > 120) return res.json({ success: false, message: "Please enter the name" });
            const web = cleanWebsite(req.body.website);
            if (!web.ok) return res.json({ success: false, message: "Please enter a valid website link, or leave it empty" });

            const [cur] = await db.promise().query(`SELECT logo FROM partners WHERE id = ? AND status != '1D'`, [id]);
            if (!cur.length) return res.json({ success: false, message: "Partner not found" });

            // a new logo replaces the old one (kept when none is uploaded)
            let logo = cur[0].logo;
            if (req.body.logo_key) {
                const moved = await keepLogo(req.body.logo_key);
                if (!moved) return res.json({ success: false, message: "The logo could not be saved, please upload it again" });
                if (logo && logo.startsWith("riviratech/partners/")) deleteS3File(logo);
                logo = moved;
            }

            await db.promise().query(`UPDATE partners SET name = ?, website = ?, logo = ? WHERE id = ?`, [name, web.value, logo, id]);
            const [rows] = await db.promise().query(`SELECT * FROM partners WHERE id = ?`, [id]);
            addactivity(req.cookies.key, String(id), "partners", "Partner updated '" + name + "'", "", "");
            res.json({ success: true, data: rows[0], message: "Partner updated" });
        } catch (err) {
            console.error(err);
            res.json({ success: false, message: "Something went wrong" });
        }
    });

    router.post("/partners-delete", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            await db.promise().query(`UPDATE partners SET status = '1D' WHERE id = ?`, [req.body.id]);
            addactivity(req.cookies.key, String(req.body.id), "partners", "Partner deleted", "", "");
            res.json({ success: true, message: "Partner deleted" });
        } catch (err) {
            console.error(err);
            res.json({ success: false, message: "Something went wrong" });
        }
    });

    router.post("/partners-reorder", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try { await applyReorder("partners", req.body.ids, res); }
        catch (err) { console.error(err); res.json({ success: false, message: "Something went wrong" }); }
    });

    router.post("/partners-toggle", async (req, res) => {
        if (!(await verifyAccount(req, res, "X,Y"))) return;
        try {
            const active = !!req.body.active;
            await db.promise().query(`UPDATE partners SET status = ? WHERE id = ?`, [active ? "1" : "1S", req.body.id]);
            res.json({ success: true, message: active ? "Shown on the home page" : "Hidden from the home page" });
        } catch (err) { console.error(err); res.json({ success: false, message: "Something went wrong" }); }
    });
};

// Tables this page owns: their deleted rows are copied to deleted_records under
// the category "admin/partners" (see ../../shared/deleted-records.js).
module.exports.tables = [
    { table: "partners" },
];
module.exports.init = ensureTable;
